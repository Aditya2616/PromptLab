from __future__ import annotations

import numpy as np

from ..prompts import Prompt
from .base import Example, Task

WORDS = (
    "apple river stone cloud lamp tiger window garden silver paper bridge candle forest "
    "pencil ocean mirror basket thunder violin copper meadow rocket button planet saddle "
    "lantern pillow harbor ladder feather castle engine marble orange pepper whistle"
).split()
LETTERS = "aeiloprst"
ORD = {1: "1st", 2: "2nd", 3: "3rd", 4: "4th", 5: "5th"}


def normalise(text: str) -> str:
    first = text.strip().splitlines()[0] if text.strip() else ""
    return first.strip().strip("`'\" .").lower().replace(" ", "")


def make_example(rng: np.random.Generator, ex_id: str) -> Example:
    kind = int(rng.integers(0, 3))
    if kind == 0:
        nums = [int(x) for x in rng.choice(np.arange(1, 100), size=4, replace=False)]
        q = f"Sort these numbers from smallest to largest: {', '.join(map(str, nums))}"
        gold = ", ".join(map(str, sorted(nums)))
    elif kind == 1:
        words = [str(w) for w in rng.choice(WORDS, size=5, replace=False)]
        n = int(rng.integers(1, 6))
        q = f"What is the {ORD[n]} word in this list: {', '.join(words)}"
        gold = words[n - 1]
    else:
        w = str(rng.choice(WORDS))
        letter = str(rng.choice(list(LETTERS)))
        q = f"How many times does the letter '{letter}' appear in the word '{w}'?"
        gold = str(w.count(letter))
    return Example(ex_id, q, gold, {"kind": kind})


class SyntheticTask(Task):
    name = "synthetic"
    title = "Synthetic transforms"
    description = (
        "Generated sort / pick-the-nth-word / count-the-letter questions. Score: the reply, "
        "normalised, must equal the answer exactly, so it rewards answering with nothing else."
    )
    max_new_tokens = 16
    source = "generated by promptlab (seeded)"

    @classmethod
    def generate(cls, dev_n: int = 80, test_n: int = 200, pool_n: int = 40, seed: int = 7) -> SyntheticTask:
        rng = np.random.default_rng(seed)
        total = pool_n + dev_n + test_n
        exs = [make_example(rng, f"s{i}") for i in range(total)]
        return cls(exs[:pool_n], exs[pool_n : pool_n + dev_n], exs[pool_n + dev_n :])

    def seeds(self) -> list[Prompt]:
        texts = [
            "You are a helpful assistant.",
            "Answer the question.",
            "Solve the following problem.",
            "You are a careful assistant. Work out the answer.",
            "Respond to the request below.",
            "Complete the task described in the message.",
        ]
        return [Prompt.from_text(t) for t in texts]

    def format_bank(self) -> list[str]:
        return [
            "Reply with only the answer, nothing else.",
            "Output just the final answer with no explanation and no full stop.",
            "Your whole reply must be the answer itself.",
            "Give the answer only.",
            "",
        ]

    def score(self, output: str, ex: Example) -> int:
        return int(normalise(output) == normalise(ex.gold))
